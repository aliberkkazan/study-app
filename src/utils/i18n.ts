export const translateCourseName = (courseName?: string | null): string => {
  if (!courseName) {
    return currentLanguage === 'tr' ? 'Genel Çalışma' : 'General Study';
  }
  const match = COURSE_TRANSLATIONS[courseName];
  if (match) {
    return match[currentLanguage] || courseName;
  }
  return courseName;
};
